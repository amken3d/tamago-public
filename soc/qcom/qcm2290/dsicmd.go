package qcm2290

// Command DMA buffer format (bmx's docs/display-spec.md §7.3): per
// packet, header bytes 1 and 2, then header byte 0 (data type | virtual
// channel << 6), then a flags byte (bit 7 last packet, bit 6 long
// packet); a long packet's payload follows, padded with 0xff to a
// multiple of 4 bytes. ECC and checksum are generated by the hardware.

// DSI data types (§7.3)
const (
	DSIGenericShort0 = 0x03
	DSIGenericShort1 = 0x13
	DSIGenericShort2 = 0x23
	DSIDCSShort0     = 0x05
	DSIDCSShort1     = 0x15
	DSIGenericLong   = 0x29
	DSIDCSLong       = 0x39

	dsiPktLast = 1 << 7
	dsiPktLong = 1 << 6
)

// DSIShortPacket returns a short packet buffer entry (virtual channel
// 0, last packet) of data type dt with parameters p0, p1.
func DSIShortPacket(dt, p0, p1 byte) []byte {
	return []byte{p0, p1, dt & 0x3f, dsiPktLast}
}

// DSILongPacket returns a long packet buffer entry (virtual channel 0,
// last packet) of data type dt, its payload padded with 0xff.
func DSILongPacket(dt byte, payload []byte) []byte {
	n := len(payload)
	b := []byte{byte(n), byte(n >> 8), dt & 0x3f, dsiPktLast | dsiPktLong}
	b = append(b, payload...)

	for len(b)%4 != 0 {
		b = append(b, 0xff)
	}

	return b
}

// DCSPacket encodes a DCS write of cmd with its parameters: a short
// packet for none or one, a long packet otherwise.
func DCSPacket(cmd byte, params ...byte) []byte {
	switch len(params) {
	case 0:
		return DSIShortPacket(DSIDCSShort0, cmd, 0)
	case 1:
		return DSIShortPacket(DSIDCSShort1, cmd, params[0])
	}

	return DSILongPacket(DSIDCSLong, append([]byte{cmd}, params...))
}

// GenericPacket encodes a generic write: a short packet for up to two
// bytes, a long packet otherwise.
func GenericPacket(data ...byte) []byte {
	switch len(data) {
	case 0:
		return DSIShortPacket(DSIGenericShort0, 0, 0)
	case 1:
		return DSIShortPacket(DSIGenericShort1, data[0], 0)
	case 2:
		return DSIShortPacket(DSIGenericShort2, data[0], data[1])
	}

	return DSILongPacket(DSIGenericLong, data)
}
