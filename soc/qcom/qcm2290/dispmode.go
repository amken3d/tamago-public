// Written from bmx's docs/display-spec.md: the tables are its Appendix A
// (the Media Carrier 800x480 DSI panel) and Appendix B (1024x600 over
// USB-C through the ANX7625), in the order to write them; see
// docs/display-provenance.md.

// RegVal is one register write: an offset from a block base and the
// value written there.
type RegVal struct {
	Off uint32
	Val uint32
}

// DisplayMode describes one display mode end to end: the DSI link, the
// clocks, the DPU pipeline and the timing a DSI receiver is told.
type DisplayMode struct {
	Name string

	// Width and Height are the active pixels; Stride the framebuffer
	// line pitch in bytes (XRGB8888, rounded up to 256).
	Width, Height, Stride int

	// Lanes is the number of DSI data lanes.
	Lanes int

	// PixelHz is the pixel clock.
	PixelHz uint64

	// Horizontal and vertical porches and sync widths, in pixels and
	// lines.
	HFP, HSync, HBP int
	VFP, VSync, VBP int

	// DISPCC configuration (§5.2, §5.3, §12.5): byte root CFG, byte
	// interface divider, pixel root CFG, MDP root CFG.
	ByteCfg, ByteIntfDiv, PixelCfg, MDPCfg uint32

	// Register tables at the DSI controller, PHY common, PHY lane and
	// PLL bases.
	DSI, PHYCommon, PHYLanes, PLL []RegVal

	// Register tables at the VBIF base and the DPU blocks.
	VBIF, Top, CTL, VIG, LM, PP, INTF []RegVal
}

// HTotal returns the pixels per line, blanking included.
func (m *DisplayMode) HTotal() int { return m.Width + m.HFP + m.HSync + m.HBP }

// VTotal returns the lines per frame, blanking included.
func (m *DisplayMode) VTotal() int { return m.Height + m.VFP + m.VSync + m.VBP }

// RefreshMilliHz returns the frame rate in mHz.
func (m *DisplayMode) RefreshMilliHz() uint64 {
	return m.PixelHz * 1000 / uint64(m.HTotal()*m.VTotal())
}

// DSI controller CTRL lane enables of the mode (§7.1): clock lane plus
// data lanes 0..Lanes-1.
func (m *DisplayMode) ctrlLanes() uint32 {
	v := uint32(dsiCtrlClockLane)

	for l := 0; l < m.Lanes; l++ {
		v |= dsiCtrlLane0 << l
	}

	return v
}

